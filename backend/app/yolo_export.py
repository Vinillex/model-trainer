"""Write a dataset manifest out as a YOLO detection dataset. No database access, so a training container can reuse it.

Layout (what Ultralytics expects):
    data.yaml
    images/{train,val,test}/<name>.<ext>
    labels/{train,val,test}/<name>.txt      one "class cx cy w h" line per box, empty file = background image
"""

import json
import tempfile
import zipfile
from collections.abc import Callable
from pathlib import Path

SPLITS = ("train", "val", "test")


class MissingImages(Exception):
    def __init__(self, missing: list[str]):
        self.missing = missing
        super().__init__(f"{len(missing)} image file(s) in this dataset version no longer exist in storage, e.g. {missing[:3]}")


def item_name(item: dict) -> str:
    return f"{item['image_id']:06d}"


def label_text(item: dict) -> str:
    return "".join(f"{c} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n" for c, cx, cy, w, h in item["boxes"])


def data_yaml(manifest: dict) -> str:
    # Written by hand: the format is trivial and this keeps the module free of dependencies.
    lines = ["# Generated by Model Trainer", "path: .", "train: images/train", "val: images/val"]
    if any(i["split"] == "test" for i in manifest["images"]):
        lines.append("test: images/test")
    lines.append("names:")
    lines += [f"  {c['index']}: {json.dumps(c['name'])}" for c in manifest["classes"]]
    return "\n".join(lines) + "\n"


def write_yolo_zip(manifest: dict, read: Callable[[str], bytes], dest: Path) -> None:
    """Stream the dataset into a zip, one file at a time, so memory stays flat however large the dataset is."""
    missing: list[str] = []
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_STORED) as zf:  # images are already compressed
        zf.writestr("data.yaml", data_yaml(manifest))
        for item in manifest["images"]:
            try:
                data = read(item["key"])
            except (FileNotFoundError, KeyError, OSError):
                missing.append(item["key"])
                continue
            name = item_name(item)
            zf.writestr(f"images/{item['split']}/{name}.{item['ext']}", data)
            zf.writestr(f"labels/{item['split']}/{name}.txt", label_text(item))
    if missing:
        dest.unlink(missing_ok=True)
        raise MissingImages(missing)


def make_zip_file(manifest: dict, read: Callable[[str], bytes]) -> Path:
    tmp = tempfile.NamedTemporaryFile(suffix=".zip", delete=False)
    tmp.close()
    path = Path(tmp.name)
    try:
        write_yolo_zip(manifest, read, path)
    except BaseException:
        path.unlink(missing_ok=True)
        raise
    return path
